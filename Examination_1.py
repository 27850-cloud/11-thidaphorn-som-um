# โจทย์ข้อที่ 1: คำนวณคะแนนเฉลี่ย 3 วิชา
# Input: บรรทัดที่ 1-3 คะแนนวิชาที่ 1, 2, 3 (จำนวนเต็ม)
# Output: คะแนนเฉลี่ย
# ==========================================


# นักเรียนเขียนโค้ดต่อจากบรรทัดนี้
s1 = int(input())
s2 = int(input())
s3 = int(input())
total = s1 + s2 + s3
discount = total / 3
print(f"คะแนนรวม{total:.2f}")
print(f"คะแนนเฉลี่ย{discount:.2f}")
